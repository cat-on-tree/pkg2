#!/usr/bin/env python
"""Aggregate a long-window diabetes carrier graph.

This script aggregates the raw selected long-window carrier graph generated by:

    scripts/25_build_long_window_diabetes_carrier_graph.py

Default input:

    data/processed/diabetes_2000_2024_v1_carrier_graph/

Default output:

    data/processed/diabetes_2000_2024_v1_carrier_graph_aggregated/

What this script does
---------------------
1. Deduplicates node tables:
   - nodes_paper.parquet by PMID
   - nodes_patent.parquet by PatentId
   - nodes_clinicaltrial.parquet by nct_id
   - nodes_project.parquet by ProjectNumber
   - nodes_bioentity.parquet by EntityId

2. Aggregates carrier-BioEntity mention edges:
   - edges_paper_bioentity.parquet by PMID + EntityId + Type + year
   - edges_patent_bioentity.parquet by PatentId + EntityId + Type + year
   - edges_trial_bioentity.parquet by nct_id + EntityId + Type + year

   Main added columns:
   - mention_count
   - distinct_mention_count
   - sample_mention
   - mention_types
   - text_fields
   - avg_prob
   - max_prob
   - evidence flags

3. Deduplicates context edges:
   - edges_patent_paper.parquet by PatentId + PMID
   - edges_paper_trial.parquet by PMID + nct_id
   - edges_paper_project.parquet by PMID + ProjectNumber
   - edges_patent_project.parquet by PatentId + ProjectNumber
   - edges_trial_project.parquet by nct_id + ProjectNumber

4. Writes:
   - aggregation_summary.json
   - graph_summary.json
   - aggregation_report.md
   - graph_manifest.csv
   - aggregation_manifest.csv

Typical run
-----------
python scripts/25b_aggregate_long_window_carrier_graph.py \
  --input-dir data/processed/diabetes_2000_2024_v1_carrier_graph \
  --output-dir data/processed/diabetes_2000_2024_v1_carrier_graph_aggregated \
  --threads 4 \
  --memory-limit 24GB \
  --overwrite
"""

