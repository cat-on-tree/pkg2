def nonempty_key_expr(column: str, alias: str = "t") -> str:
    return f"NULLIF(TRIM(CAST({alias}.{qident(column)} AS VARCHAR)), '')"


def any_value_expr(columns: set[str], column: str, output_name: str | None = None, alias: str = "t") -> str:
    out = output_name or column
    if column in columns:
        return f"ANY_VALUE({alias}.{qident(column)}) AS {qident(out)}"
    return f"CAST(NULL AS VARCHAR) AS {qident(out)}"


def double_expr(columns: set[str], column: str, alias: str = "t") -> str:
    if column in columns:
        return f"TRY_CAST({alias}.{qident(column)} AS DOUBLE)"
    return "CAST(NULL AS DOUBLE)"


def bigint_expr(columns: set[str], column: str, alias: str = "t") -> str:
    if column in columns:
        return f"TRY_CAST({alias}.{qident(column)} AS BIGINT)"
    return "CAST(NULL AS BIGINT)"


def string_agg_distinct_expr(
    columns: set[str],
    column: str,
    output_name: str,
    alias: str = "t",
) -> str:
    if column in columns:
        value_expr = f"NULLIF(TRIM(CAST({alias}.{qident(column)} AS VARCHAR)), '')"
        return (
            f"STRING_AGG(DISTINCT {value_expr}, '|') "
            f"FILTER (WHERE {value_expr} IS NOT NULL) AS {qident(output_name)}"
        )
    return f"CAST(NULL AS VARCHAR) AS {qident(output_name)}"


def count_distinct_expr(
    columns: set[str],
    column: str,
    output_name: str,
    alias: str = "t",
) -> str:
    if column in columns:
        value_expr = f"NULLIF(TRIM(CAST({alias}.{qident(column)} AS VARCHAR)), '')"
        return f"COUNT(DISTINCT {value_expr}) AS {qident(output_name)}"
    return f"CAST(0 AS BIGINT) AS {qident(output_name)}"


def flag_expr(columns: set[str], column: str, output_name: str, alias: str = "t") -> str:
    if column in columns:
        value_expr = f"NULLIF(TRIM(CAST({alias}.{qident(column)} AS VARCHAR)), '')"
        return (
            f"MAX(CASE WHEN {value_expr} IS NOT NULL THEN 1 ELSE 0 END) "
            f"AS {qident(output_name)}"
        )
    return f"CAST(0 AS INTEGER) AS {qident(output_name)}"


def create_deduplicated_node_tables(connection: Any) -> list[dict[str, Any]]:
    stats: list[dict[str, Any]] = []

    for table_name, meta in NODE_FILES.items():
        input_table = "input_" + table_name
        id_col = str(meta["id_column"])

        raw_count = count_table(connection, input_table)

        columns = get_columns(connection, input_table)

        # Use an explicit alias because nonempty_key_expr(..., alias="t")
        # generates expressions like t."PMID".
        id_expr = nonempty_key_expr(id_col, alias="t")

        if "year" in columns:
            order_expr = "TRY_CAST(t.\"year\" AS BIGINT) NULLS LAST"
        else:
            order_expr = id_expr

        execute(
            connection,
            f"""
            CREATE TEMP TABLE {qident(table_name)} AS
            SELECT * EXCLUDE (__rn)
            FROM (
                SELECT
                    t.*,
                    ROW_NUMBER() OVER (
                        PARTITION BY {id_expr}
                        ORDER BY {order_expr}
                    ) AS __rn
                FROM {qident(input_table)} t
                WHERE {id_expr} IS NOT NULL
            )
            WHERE __rn = 1
            """,
        )

        output_count = count_table(connection, table_name)

        stats.append(
            {
                "table": table_name,
                "file_name": meta["file_name"],
                "id_column": id_col,
                "raw_rows": raw_count,
                "deduplicated_rows": output_count,
                "removed_rows": raw_count - output_count,
            }
        )

    return stats


def create_deduplicated_context_edge_table(
    connection: Any,
    *,
    input_table_name: str,
    output_table_name: str,
    key_columns: list[str],
) -> dict[str, Any]:
    input_table = "input_" + input_table_name
    columns = get_columns(connection, input_table)

    raw_count = count_table(connection, input_table)

    normalized_key_items = [
        f"{nonempty_key_expr(column, alias='t')} AS {qident(column)}"
        for column in key_columns
    ]

    key_predicates = [
        f"{nonempty_key_expr(column, alias='t')} IS NOT NULL"
        for column in key_columns
    ]

    # Keep non-key columns as aggregated metadata. Avoid SELECT *, because
    # SELECT normalized_key AS PMID, * can create duplicate column names and
    # make later references brittle.
    aggregate_exprs: list[str] = []

    for column in sorted(columns):
        if column in key_columns:
            continue

        if column == "RecordYear":
            aggregate_exprs.append(
                f"MIN(TRY_CAST(t.{qident(column)} AS BIGINT)) AS min_record_year"
            )
            aggregate_exprs.append(
                f"MAX(TRY_CAST(t.{qident(column)} AS BIGINT)) AS max_record_year"
            )
            aggregate_exprs.append(any_value_expr(columns, column, column, alias="t"))
        else:
            aggregate_exprs.append(any_value_expr(columns, column, column, alias="t"))

    select_items = [
        *normalized_key_items,
        "COUNT(*) AS edge_record_count",
        *aggregate_exprs,
    ]

    group_by_items = [
        nonempty_key_expr(column, alias="t")
        for column in key_columns
    ]

    execute(
        connection,
        f"""
        CREATE TEMP TABLE {qident(output_table_name)} AS
        SELECT
            {", ".join(select_items)}
        FROM {qident(input_table)} t
        WHERE {" AND ".join(key_predicates)}
        GROUP BY {", ".join(group_by_items)}
        """,
    )

    output_count = count_table(connection, output_table_name)

    return {
        "edge_table": output_table_name,
        "raw_edge_rows": raw_count,
        "deduplicated_edge_rows": output_count,
        "removed_duplicate_rows": raw_count - output_count,
        "key_columns": "|".join(key_columns),
    }


def create_deduplicated_context_edge_tables(connection: Any) -> list[dict[str, Any]]:
    stats: list[dict[str, Any]] = []

    for table_name, meta in CONTEXT_EDGE_FILES.items():
        stats.append(
            create_deduplicated_context_edge_table(
                connection,
                input_table_name=table_name,
                output_table_name=table_name,
                key_columns=list(meta["key_columns"]),
            )
        )

    return stats


def create_aggregated_bioentity_edge_table(
    connection: Any,
    *,
    input_table_name: str,
    output_table_name: str,
    carrier_id_column: str,
    carrier_type: str,
    node_table: str,
) -> dict[str, Any]:
    input_table = "input_" + input_table_name

    columns = get_columns(connection, input_table)
    raw_count = count_table(connection, input_table)

    carrier_expr = nonempty_key_expr(carrier_id_column, alias="e")
    entity_expr = nonempty_key_expr("EntityId", alias="e")

    # Entity Type can be noisy but is important for KU pair-type construction.
    # Keep Type in the grouping key.
    type_expr = (
        "NULLIF(TRIM(CAST(e.\"Type\" AS VARCHAR)), '')"
        if "Type" in columns
        else "CAST(NULL AS VARCHAR)"
    )

    # Carrier year is taken from deduplicated carrier node tables.
    # The long-window builder writes a canonical `year` column to carrier nodes.
    node_id_col = carrier_id_column

    mention_expr = any_value_expr(columns, "Mention", "sample_mention", alias="e")
    mention_type_expr = any_value_expr(columns, "Type", "sample_mention_type", alias="e")
    distinct_mention_expr = count_distinct_expr(columns, "Mention", "distinct_mention_count", alias="e")
    mention_types_expr = string_agg_distinct_expr(columns, "Type", "mention_types", alias="e")
    text_fields_expr = string_agg_distinct_expr(columns, "TextFrom", "text_fields", alias="e")

    min_start_expr = f"MIN({bigint_expr(columns, 'StartPosition', alias='e')}) AS min_start_position"
    max_end_expr = f"MAX({bigint_expr(columns, 'EndPosition', alias='e')}) AS max_end_position"
    avg_prob_expr = f"AVG({double_expr(columns, 'prob', alias='e')}) AS avg_prob"
    max_prob_expr = f"MAX({double_expr(columns, 'prob', alias='e')}) AS max_prob"

    has_neural_expr = flag_expr(columns, "is_neural_normalized", "has_neural_normalized", alias="e")
    has_mesh_expr = flag_expr(columns, "mesh", "has_mesh", alias="e")
    has_mim_expr = flag_expr(columns, "mim", "has_mim", alias="e")
    has_cl_expr = flag_expr(columns, "CL", "has_cl", alias="e")
    has_cellosaurus_expr = flag_expr(columns, "cellosaurus", "has_cellosaurus", alias="e")
    has_ncbitaxon_expr = flag_expr(columns, "NCBITaxon", "has_ncbitaxon", alias="e")
    has_ncbigene_expr = flag_expr(columns, "NCBIGene", "has_ncbigene", alias="e")
    has_chebi_expr = flag_expr(columns, "CHEBI", "has_chebi", alias="e")
    source_files_expr = string_agg_distinct_expr(columns, "FileName", "source_files", alias="e")

    execute(
        connection,
        f"""
        CREATE TEMP TABLE {qident(output_table_name)} AS
        WITH normalized AS (
            SELECT
                {carrier_expr} AS carrier_id,
                {entity_expr} AS EntityId,
                {type_expr} AS Type,
                n.year AS year,
                e.*
            FROM {qident(input_table)} e
            INNER JOIN {qident(node_table)} n
                ON {carrier_expr} = NULLIF(TRIM(CAST(n.{qident(node_id_col)} AS VARCHAR)), '')
            WHERE {carrier_expr} IS NOT NULL
              AND {entity_expr} IS NOT NULL
              AND n.year IS NOT NULL
        )
        SELECT
            carrier_id AS {qident(carrier_id_column)},
            EntityId,
            Type,
            year,
            {sql_literal(carrier_type)} AS carrier_type,
            'carrier_bioentity_year' AS aggregation_level,
            COUNT(*) AS mention_count,
            {distinct_mention_expr},
            {mention_expr},
            {mention_type_expr},
            {mention_types_expr},
            {text_fields_expr},
            {source_files_expr},
            {min_start_expr},
            {max_end_expr},
            {avg_prob_expr},
            {max_prob_expr},
            {has_neural_expr},
            {has_mesh_expr},
            {has_mim_expr},
            {has_cl_expr},
            {has_cellosaurus_expr},
            {has_ncbitaxon_expr},
            {has_ncbigene_expr},
            {has_chebi_expr}
        FROM normalized e
        GROUP BY
            carrier_id,
            EntityId,
            Type,
            year
        """,
    )

    output_count = count_table(connection, output_table_name)

    duplicate_rows_removed = raw_count - output_count
    compression_ratio = raw_count / output_count if output_count else None

    return {
        "edge_table": output_table_name,
        "carrier_type": carrier_type,
        "carrier_id_column": carrier_id_column,
        "raw_mention_edge_count": raw_count,
        "aggregated_edge_count": output_count,
        "removed_duplicate_rows": duplicate_rows_removed,
        "compression_ratio_raw_to_aggregated": f"{compression_ratio:.3f}" if compression_ratio else "",
    }


