def print_summary(
    output_dir: Path,
    counts: dict[str, int],
    bioedge_stats: list[dict[str, Any]],
    context_edge_stats: list[dict[str, Any]],
) -> None:
    print()
    print("Long-window carrier graph aggregation complete")
    print(f"Output directory: {output_dir}")
    print()

    print("BioEntity edge aggregation stats:")
    for row in bioedge_stats:
        print(
            f"- {row['edge_table']}: "
            f"raw={row['raw_mention_edge_count']:,}, "
            f"aggregated={row['aggregated_edge_count']:,}, "
            f"compression={row['compression_ratio_raw_to_aggregated']}"
        )

    print()
    print("Context edge deduplication stats:")
    for row in context_edge_stats:
        print(
            f"- {row['edge_table']}: "
            f"raw={row['raw_edge_rows']:,}, "
            f"deduplicated={row['deduplicated_edge_rows']:,}"
        )

    print()
    print("Final counts:")
    for key, value in build_graph_scale(counts).items():
        print(f"- {key}: {value:,}")

    print()
    print(f"Report: {output_dir / 'aggregation_report.md'}")
    print(f"Manifest: {output_dir / 'graph_manifest.csv'}")
    print()


def main() -> None:
    args = parse_args()
    start_time = time.time()

    if args.threads < 1:
        raise ValueError("--threads must be >= 1")

    args.input_dir = args.input_dir.resolve()
    args.output_dir = args.output_dir.resolve()
    args.temp_dir = args.temp_dir.resolve()

    require_files(args.input_dir)
    prepare_output_dir(args.output_dir, args.overwrite)

    connection = connect_duckdb(args)

    run_step(
        args,
        1,
        8,
        "Creating input graph views",
        lambda: create_input_views(connection, args.input_dir),
    )

    node_stats = run_step(
        args,
        2,
        8,
        "Deduplicating node tables",
        lambda: create_deduplicated_node_tables(connection),
    )

    context_edge_stats = run_step(
        args,
        3,
        8,
        "Deduplicating context edge tables",
        lambda: create_deduplicated_context_edge_tables(connection),
    )

    bioedge_stats = run_step(
        args,
        4,
        8,
        "Aggregating BioEntity mention edge tables",
        lambda: create_aggregated_bioentity_edge_tables(connection),
    )

    counts = run_step(
        args,
        5,
        8,
        "Counting aggregated outputs",
        lambda: count_outputs(connection),
    )

    manifest_rows = run_step(
        args,
        6,
        8,
        "Writing Parquet outputs",
        lambda: write_outputs(connection, args, counts),
    )

    runtime_seconds = time.time() - start_time

    run_step(
        args,
        7,
        8,
        "Writing summaries and manifests",
        lambda: (
            write_aggregation_stats(
                args.output_dir,
                node_stats,
                bioedge_stats,
                context_edge_stats,
            ),
            write_summary_json(
                args.output_dir,
                args,
                runtime_seconds,
                counts,
                node_stats,
                bioedge_stats,
                context_edge_stats,
            ),
            write_manifest_files(args.output_dir, manifest_rows),
        ),
    )

    run_step(
        args,
        8,
        8,
        "Writing aggregation report",
        lambda: write_report(
            args.output_dir,
            args,
            runtime_seconds,
            counts,
            node_stats,
            bioedge_stats,
            context_edge_stats,
            manifest_rows,
        ),
    )

    print_summary(args.output_dir, counts, bioedge_stats, context_edge_stats)


if __name__ == "__main__":
    main()