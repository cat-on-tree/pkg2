def write_report(
    output_dir: Path,
    args: argparse.Namespace,
    runtime_seconds: float,
    counts: dict[str, int],
    node_stats: list[dict[str, Any]],
    bioedge_stats: list[dict[str, Any]],
    context_edge_stats: list[dict[str, Any]],
    manifest_rows: list[dict[str, Any]],
) -> None:
    graph_scale = build_graph_scale(counts)

    parameter_rows = [
        {"parameter": "input_dir", "value": str(args.input_dir)},
        {"parameter": "output_dir", "value": str(args.output_dir)},
        {"parameter": "threads", "value": args.threads},
        {"parameter": "memory_limit", "value": args.memory_limit},
        {"parameter": "compression", "value": args.compression},
        {"parameter": "runtime_seconds", "value": f"{runtime_seconds:.1f}"},
    ]

    scale_rows = [{"metric": key, "count": value} for key, value in graph_scale.items()]

    parts = ["# Long-window Carrier Graph Aggregation Report\n"]

    parts.append("## 1. Parameters\n")
    parts.append(markdown_table(parameter_rows, ["parameter", "value"]))

    parts.append("\n## 2. Aggregation rule\n")
    parts.append(
        "Carrier-BioEntity mention edges are aggregated by "
        "`carrier_id + EntityId + Type + year`. The primary edge weight is "
        "`mention_count`. Carrier year is joined from the corresponding "
        "deduplicated carrier node table. Context edges are deduplicated by "
        "their endpoint key columns.\n"
    )

    parts.append("\n## 3. Final graph scale\n")
    parts.append(markdown_table(scale_rows, ["metric", "count"]))

    parts.append("\n## 4. Node deduplication stats\n")
    parts.append(
        markdown_table(
            node_stats,
            [
                "table",
                "id_column",
                "raw_rows",
                "deduplicated_rows",
                "removed_rows",
            ],
        )
    )

    parts.append("\n## 5. BioEntity edge aggregation stats\n")
    parts.append(
        markdown_table(
            bioedge_stats,
            [
                "edge_table",
                "carrier_type",
                "raw_mention_edge_count",
                "aggregated_edge_count",
                "removed_duplicate_rows",
                "compression_ratio_raw_to_aggregated",
            ],
        )
    )

    parts.append("\n## 6. Context edge deduplication stats\n")
    parts.append(
        markdown_table(
            context_edge_stats,
            [
                "edge_table",
                "raw_edge_rows",
                "deduplicated_edge_rows",
                "removed_duplicate_rows",
                "key_columns",
            ],
        )
    )

    parts.append("\n## 7. Output artifacts\n")
    parts.append(
        markdown_table(
            manifest_rows,
            ["artifact_type", "name", "path", "row_count", "description"],
        )
    )

    parts.append("\n## 8. Recommended next step\n")
    parts.append(
        "Use this aggregated graph as input to Stage 04/05 KU construction:\n\n"
        "```bash\n"
        "python scripts/20_build_knowledge_units.py \\\n"
        "  --graph-dir data/processed/diabetes_2000_2024_v1_carrier_graph_aggregated \\\n"
        "  --output-dir data/datasets/knowledge_units/diabetes_2000_2024_v1_translational \\\n"
        "  --exclude-bioentity-types species \\\n"
        "  --pair-types chemical-disease gene-disease chemical-gene \\\n"
        "  --min-carrier-count 3 \\\n"
        "  --max-entities-per-carrier 0 \\\n"
        "  --overwrite\n"
        "```\n"
    )

    report_text = "\n".join(parts)
    (output_dir / "aggregation_report.md").write_text(report_text, encoding="utf-8")


